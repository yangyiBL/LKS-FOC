
#include "hardware_config.h"

void Hardware_init(void);
void Task_Scheduler(void);
void sys_init(void);

/*******************************************************************************
 函数名称：    int main(void)
 功能描述：    主程序入口
 输入参数：    无
 输出参数：    无
 返 回 值：    无
 其它说明：
 修改日期      版本号          修改人            修改内容
 -----------------------------------------------------------------------------
 2020/8/5      V1.0           Howlet Li          创建
 *******************************************************************************/
int main(void)
{
    Hardware_init();      /* 硬件初始化 */

    sys_init();           /* 系统初始化 */
  
    for(;;)
    { 
        Task_Scheduler(); /* 任务调度函数，根据时间分片处理 */
    }
}

